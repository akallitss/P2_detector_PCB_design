# ---------------------------------------------------------------- helpers
def outline(ax, wires, i, j, fill=C_PART, lw=0.9):
    for w in wires:
        xs, ys = [p[i] for p in w], [p[j] for p in w]
        ax.fill(xs, ys, color=fill, zorder=2)
        ax.plot(xs, ys, color=INK, lw=lw, zorder=3)


def outline_holes(ax, wires, i, j):
    """Outer wire filled, the others (holes) punched white."""
    areas = []
    for w in wires:
        xs, ys = [p[i] for p in w], [p[j] for p in w]
        a = 0.5 * abs(sum(xs[k] * ys[k + 1] - xs[k + 1] * ys[k] for k in range(len(xs) - 1)))
        areas.append(a)
    order = sorted(range(len(wires)), key=lambda k: -areas[k])
    for n, k in enumerate(order):
        w = wires[k]
        xs, ys = [p[i] for p in w], [p[j] for p in w]
        ax.fill(xs, ys, color=C_PART if n == 0 or areas[k] > 0.5 * areas[order[0]] else "white", zorder=2 + n * 0.01)
        ax.plot(xs, ys, color=INK, lw=0.9, zorder=3)


def dim(ax, a, b, off, text, vertical=False, fs=7, ext=True):
    """Dimension between points a and b, drawn `off` away (perpendicular)."""
    (x0, y0), (x1, y1) = a, b
    if vertical:
        xd = x0 + off
        if ext:
            ax.plot([x0, xd], [y0, y0], color=DIM, lw=0.4); ax.plot([x1, xd], [y1, y1], color=DIM, lw=0.4)
        ax.annotate("", (xd, y0), (xd, y1), arrowprops=dict(arrowstyle="<|-|>", color=DIM, lw=0.6, mutation_scale=6))
        ax.text(xd, (y0 + y1) / 2, " " + text + " ", color=DIM, fontsize=fs, rotation=90, ha="center", va="center",
                bbox=dict(fc="white", ec="none", pad=0.4))
    else:
        yd = y0 + off
        if ext:
            ax.plot([x0, x0], [y0, yd], color=DIM, lw=0.4); ax.plot([x1, x1], [y1, yd], color=DIM, lw=0.4)
        ax.annotate("", (x0, yd), (x1, yd), arrowprops=dict(arrowstyle="<|-|>", color=DIM, lw=0.6, mutation_scale=6))
        ax.text((x0 + x1) / 2, yd, text, color=DIM, fontsize=fs, ha="center", va="center",
                bbox=dict(fc="white", ec="none", pad=0.4))


def note(ax, x, y, text, **kw):
    ax.text(x, y, text, fontsize=kw.pop("fs", 7), color=kw.pop("color", INK), **kw)


