ADVANCE = 5.5          # grid units from one glyph origin to the next
HEIGHT = 6.0           # grid units for a capital


def text_width(s: str, height_mm: float) -> float:
    k = height_mm / HEIGHT
    return (len(s) * ADVANCE - (ADVANCE - 4)) * k if s else 0.0


def text(s: str, x: float, y: float, height_mm: float, angle_deg: float = 0.0):
    """Polylines (lists of (x, y) in mm) for `s`, baseline-left at (x, y)."""
    import math
    k = height_mm / HEIGHT
    ca, sa = math.cos(math.radians(angle_deg)), math.sin(math.radians(angle_deg))
    out = []
    for i, ch in enumerate(s.upper()):
        for stroke in G.get(ch, G["?"] if "?" in G else []):
            pts = []
            for gx, gy in stroke:
                ux, uy = (i * ADVANCE + gx) * k, gy * k
                pts.append((x + ca * ux - sa * uy, y + sa * ux + ca * uy))
            out.append(pts)
    return out
